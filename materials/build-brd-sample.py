"""Build assets/brd-sample.js from the NHS England Monthly A&E Time Series (real public rows).

    python3 -m pip install xlrd pandas
    python3 materials/build-brd-sample.py <path to Monthly-AE-Time-Series-September-2026-LS35fw.xls>

Source file (Open Government Licence v3.0, published 8 October 2026):
https://www.england.nhs.uk/statistics/wp-content/uploads/sites/2/2026/10/Monthly-AE-Time-Series-September-2026-LS35fw.xls
linked from https://www.england.nhs.uk/statistics/statistical-work-areas/ae-waiting-times-and-activity/
Sheet "Performance", column "Percentage in 4 hours or less (all)", England, all A&E types.

Window: June 2023 (the first month after the Clinical Review of Standards field test ended, so all
trusts report four-hour data again) to September 2026. Values are stored as basis points
(percent x 100, rounded half away from zero) so the browser engine and the Python reference
compare integers. Interim targets are the end-of-year milestones in NHS England's planning
documents, applied to every month of that financial year (a convention, labelled on the widget).
"""
import json
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import pandas as pd

SRC = sys.argv[1]
OUT = Path(__file__).resolve().parent.parent / "assets" / "brd-sample.js"

df = pd.read_excel(SRC, sheet_name="Performance", header=None)
hdr = [str(v) for v in df.iloc[13].tolist()]
c_pct = hdr.index("Percentage in 4 hours or less (all)")
c_in, c_out = hdr.index("Total Attendances < 4 hours"), hdr.index("Total Attendances > 4 hours")

rows = []
for i in range(14, len(df)):
    d = df.iloc[i, 1]
    if pd.isna(d):
        continue
    ym = pd.Timestamp(d).strftime("%Y-%m")
    if not ("2023-06" <= ym <= "2026-09"):
        continue
    pct = float(df.iloc[i, c_pct])
    bp = int(Decimal(repr(pct * 10000)).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
    rows.append((ym, bp, float(df.iloc[i, c_in]), float(df.iloc[i, c_out])))


def fy(ym):
    y, m = int(ym[:4]), int(ym[5:])
    return y if m >= 4 else y - 1


INTERIM = {2023: 7600, 2024: 7800, 2025: 7800, 2026: 8200}

# cross-check against the NAO's published 2025-26 figure (74.9%), attendance-weighted
fy25 = [r for r in rows if fy(r[0]) == 2025]
w = sum(r[2] for r in fy25) / sum(r[2] + r[3] for r in fy25)
print("months", len(rows), rows[0][0], "to", rows[-1][0])
print("FY2025-26 attendance-weighted within 4 hours: %.2f%% (NAO reports 74.9%%)" % (100 * w))

sample = {
    "source": {
        "title": "A&E Attendances and Emergency Admissions, Monthly A&E Time Series September 2026",
        "publisher": "NHS England",
        "published": "8 October 2026",
        "url": "https://www.england.nhs.uk/statistics/statistical-work-areas/ae-waiting-times-and-activity/",
        "file": "Monthly-AE-Time-Series-September-2026-LS35fw.xls",
        "sheet": "Performance, column: Percentage in 4 hours or less (all)",
        "licence": "Open Government Licence v3.0",
    },
    "months": [r[0] for r in rows],
    "pct_bp": [r[1] for r in rows],
    "interim_bp": [INTERIM[fy(r[0])] for r in rows],
    "formal_bp": 9500,
    "first_rated": "2024-04",
}
OUT.write_text(
    "/* brd-sample.js - generated by materials/build-brd-sample.py with json.dumps. Real rows: NHS England,\n"
    " * Monthly A&E Time Series September 2026, England, all A&E types, share of attendances within four\n"
    " * hours, in basis points (7436 = 74.36%). Open Government Licence v3.0. */\n"
    "window.BRD_SAMPLE = " + json.dumps(sample, separators=(",", ":")) + ";\n"
)
print("wrote", OUT, OUT.stat().st_size, "bytes")
